final Random _secureRandom = Random.secure();

String generatePassphrase({
  int wordCount = defaultPassphraseWordCount,
  PassphraseIndexPicker? pickIndex,
}) {
  assert(wordCount > 0);
  final picker = pickIndex ?? _secureRandom.nextInt;
  return List.generate(
    wordCount,
    (_) => _passphraseWords[picker(_passphraseWords.length)],
  ).join(' ');
}
