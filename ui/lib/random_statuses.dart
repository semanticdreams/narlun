String pickRandomStatus({
  String? excluding,
  Random? random,
}) {
  final generator = random ?? Random();
  if (randomStatuses.length <= 1) {
    return randomStatuses.first;
  }
  final trimmedExcluding = excluding?.trim();
  final candidates = trimmedExcluding == null || trimmedExcluding.isEmpty
      ? randomStatuses
      : randomStatuses
            .where((status) => status != trimmedExcluding)
            .toList(growable: false);
  final source = candidates.isEmpty ? randomStatuses : candidates;
  return source[generator.nextInt(source.length)];
}
